import {ParseLifecycle,LARGE_LIMIT,FILE_LIMIT,MARKER_KEY} from '../parse-lifecycle.js';
import {createParseClient} from '../core/parse-client.js';
const results=[];const assert=(name,pass)=>results.push({name,pass:!!pass});
const file=(name,size=1)=>({name,size,arrayBuffer:async()=>new ArrayBuffer(1)});
const manager=(ms=100)=>new ParseLifecycle({timeoutMs:ms,client:createParseClient({workerUrl:'./controlled-worker.js'})});
localStorage.removeItem(MARKER_KEY);
let m=manager();let r=await m.start(file('ok.dxf'));assert('成功回傳',r.status==='done'&&r.value.name==='ok.dxf');
r=await m.start(file('error.dxf'));assert('失敗回傳',r.status==='error');
r=await m.start(file('ok.dxf'));assert('失敗後可重試',r.status==='done');
r=await m.start(file('hang.dxf'));assert('逾時停止',r.status==='timeout');
r=await m.start(file('ok.dxf'));assert('逾時後可重試',r.status==='done');
let pending=m.start(file('hang.dxf'));m.cancel();r=await pending;assert('取消完成',r.status==='cancelled'&&m.current===null);
const first=m.start(file('slow.dxf'));const second=m.start(file('ok.dxf'));const a=await first,b=await second;await new Promise(r=>setTimeout(r,350));assert('舊工作不可覆蓋新結果',a.status==='cancelled'&&b.status==='done'&&b.value.name==='ok.dxf'&&m.current===null);
r=await m.start(file('ok.dxf',FILE_LIMIT+1));assert('超過上限拒絕',r.status==='too-large');
r=await m.start(file('ok.dxf',FILE_LIMIT));assert('上限內可啟動',r.status==='done');
pending=m.start(file('hang.dxf',LARGE_LIMIT+1));assert('大型檔啟動時記錄',!!localStorage.getItem(MARKER_KEY));m.cancel();await pending;assert('取消後清除記錄',!localStorage.getItem(MARKER_KEY));
pending=m.start(file('hang.dxf',LARGE_LIMIT));assert('10 MiB 不記錄',!localStorage.getItem(MARKER_KEY));m.cancel();await pending;
pending=m.start(file('hang.dxf',LARGE_LIMIT+1));let m2=manager();assert('重開可偵測記錄',m2.interrupted());m2.clearInterrupted();assert('略過可清除記錄',!m2.interrupted());m.cancel();await pending;
window.testResults=results;document.body.textContent=JSON.stringify(results);
